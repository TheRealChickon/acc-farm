"""Builds src/data.lua (towers, waves with pack rewards, story worlds) from the macro's towers.json + story.json.
Usage: python3 tools/build_data.py <towers.json> <story.json>"""
import json, sys, os

def rolls(rewards):
    n = 0
    for r in rewards:
        it = str(r.get("item", ""))
        if it.startswith("instant_roll_"):
            try: n += int(it.rsplit("_", 1)[1]) * r.get("count", 1)
            except ValueError: pass
    return n

def lua(v, ind=""):
    if isinstance(v, bool): return "true" if v else "false"
    if v is None: return "nil"
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, list): return "{" + ", ".join(lua(x) for x in v) + "}"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k} = {lua(x)}" if k.isidentifier() else f"[{json.dumps(k)}] = {lua(x)}" for k, x in v.items()) + "}"
    raise TypeError(v)

towers = json.load(open(sys.argv[1]))["towers"]
story = json.load(open(sys.argv[2]))["worlds"]
T = []
for t in towers:
    first = {str(w["wave"]): rolls(w["first"]) for w in t["waves"] if rolls(w["first"])}
    rep = {str(w["wave"]): rolls(w["repeat"]) for w in t["waves"] if rolls(w["repeat"])}
    T.append({"id": t["id"], "name": t["short"] if t["group"] == "main" else t["name"].split(" · ")[-1], "group": t["group"],
              "waves": len(t["waves"]), "floorsPerWave": t["floorsPerWave"],
              "requires": t["requires"] and {"mode": t["requires"]["mode"], "wave": t["requires"]["wave"]},
              "firstRolls": first, "repeatRolls": rep})
DIFFS = ["normal", "medium", "hard", "extreme", "nightmare", "celestial"]
W = []
for w in story:
    bosses = {}
    for st in w["stages"]:
        bosses.setdefault(st["difficulty"], []).append({"boss": st["boss"], "name": st["bossName"], "stage": st["stage"], "rolls": rolls(st["repeat"])})
    W.append({"id": w["id"], "name": w["name"], "crystal": (w.get("storyTower") or {}).get("crystal"),
              "crystalFloor": (w.get("storyTower") or {}).get("crystalFloor"),
              "bosses": {d: sorted(bosses.get(d, []), key=lambda b: b["stage"]) for d in DIFFS}})
out = ["-- Generated by tools/build_data.py from the macro's towers.json + story.json (game 9.6.0). Do not edit by hand.",
       "return {", "  difficulties = " + lua(DIFFS) + ",", "  towers = {"]
out += ["    " + lua(t) + "," for t in T]
out += ["  },", "  worlds = {"]
out += ["    " + lua(w) + "," for w in W]
out += ["  },", "}"]
os.makedirs("src", exist_ok=True)
open("src/data.lua", "w").write("\n".join(out) + "\n")
print("towers", len(T), "worlds", len(W), "bytes", os.path.getsize("src/data.lua"))
